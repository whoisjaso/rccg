#!/usr/bin/env python3
"""Install a returned (AI-generated or edited) image into a site slot.

Usage:
  python install_slot.py <image> <slots-dir> <slot-name> [--sizes 2400,1280] [--prompt "provenance text"] [--keep-dir source-assets/generated]

- Keeps the native resolution for the largest size (never upscales) and saves it under the
  largest slot filename, so pages need no renaming; prints the true width for srcset.
- Writes a .json provenance sidecar next to each file.
- Copies the untouched original to --keep-dir so the user can switch back any time.
"""
import argparse, json, shutil, datetime
from pathlib import Path
from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument("image"); ap.add_argument("slots_dir"); ap.add_argument("slot")
ap.add_argument("--sizes", default="2400,1280")
ap.add_argument("--prompt", default="Generated by the user from the project's image brief.")
ap.add_argument("--keep-dir", default="source-assets/generated")
a = ap.parse_args()

src = Path(a.image); out = Path(a.slots_dir); out.mkdir(parents=True, exist_ok=True)
keep = Path(a.keep_dir); keep.mkdir(parents=True, exist_ok=True)
shutil.copy(src, keep / f"{a.slot}-original{src.suffix}")
im = Image.open(src).convert("RGB")
sizes = sorted((int(s) for s in a.sizes.split(",")), reverse=True)
stamp = datetime.datetime.now(datetime.timezone.utc).isoformat()
for i, w in enumerate(sizes):
    r = im if (i == 0 or im.width <= w) else im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    f = out / f"{a.slot}-{w}.webp"
    r.save(f, "WEBP", quality=88 if i == 0 else 86, method=6)
    Path(str(f) + ".json").write_text(json.dumps({"prompt": a.prompt, "createdAt": stamp}, indent=2))
    print(f"{f}  actual {r.size[0]}x{r.size[1]}  -> srcset descriptor {r.size[0]}w")
